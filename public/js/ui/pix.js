const FLASK_COL = { hp_potion: ["#ff7a7a", "#c8202e"], mp_potion: ["#8ac0ff", "#2a5ad0"], antidote: ["#9ae88a", "#2a9a3a"] };

const cache = new Map();
function draw(rows, pal, scale) {
  const cv = document.createElement("canvas");
  cv.width = 12 * scale; cv.height = 12 * scale;
  const g = cv.getContext("2d");
  rows.forEach((row, y) => [...row].forEach((ch, x) => { const c = pal[ch]; if (c) { g.fillStyle = c; g.fillRect(x * scale, y * scale, scale, scale); } }));
  return cv.toDataURL();
}
/** 픽셀 아이콘 data URL */
export function pix(name, scale = 3) {
  const key = name + "@" + scale;
  if (!cache.has(key)) {
    if (FLASK_COL[name]) { const [a, b] = FLASK_COL[name]; cache.set(key, draw(FLASK, { ...PAL, 1: a, 2: b }, scale)); }
    else if (ICONS[name]) cache.set(key, draw(ICONS[name], PAL, scale));
    else return "";
  }
  return cache.get(key);
}
/** <img> 아이콘 */
export function pixImg(name, cls = "pi", scale = 3) {
  const im = document.createElement("img");
  im.className = cls; im.src = pix(name, scale); im.alt = ""; im.draggable = false;
  return im;
}
